CREATE DATABASE vaccination_db;

USE vaccination_db;

CREATE TABLE coverage (
    coverage_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    `GROUP` VARCHAR(50),
    CODE VARCHAR(10),
    NAME VARCHAR(150),
    YEAR INT,
    ANTIGEN VARCHAR(50),
    ANTIGEN_DESCRIPTION VARCHAR(255),
    COVERAGE_CATEGORY VARCHAR(100),
    COVERAGE_CATEGORY_DESCRIPTION VARCHAR(255),
    TARGET_NUMBER BIGINT,
    DOSES BIGINT,
    COVERAGE DECIMAL(8,2)
);

CREATE TABLE incidence_rate (
    incidence_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    `GROUP` VARCHAR(50),
    CODE VARCHAR(10),
    NAME VARCHAR(150),
    YEAR INT,
    DISEASE VARCHAR(50),
    DISEASE_DESCRIPTION VARCHAR(255),
    DENOMINATOR BIGINT,
    INCIDENCE_RATE DECIMAL(12,4)
);

CREATE TABLE reported_cases (
    case_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    `GROUP` VARCHAR(50),
    CODE VARCHAR(10),
    NAME VARCHAR(150),
    YEAR INT,
    DISEASE VARCHAR(50),
    DISEASE_DESCRIPTION VARCHAR(255),
    CASES BIGINT
);

CREATE TABLE vaccine_introduction (
    introduction_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    ISO_3_CODE CHAR(3),
    COUNTRYNAME VARCHAR(150),
    WHO_REGION VARCHAR(100),
    YEAR INT,
    DESCRIPTION VARCHAR(255),
    INTRO VARCHAR(50)
);

