    TARGETPOP VARCHAR(100),
    TARGETPOP_DESCRIPTION VARCHAR(255),
    GEOAREA VARCHAR(255),
    AGEADMINISTERED VARCHAR(100),
    SOURCECOMMENT TEXT
);


